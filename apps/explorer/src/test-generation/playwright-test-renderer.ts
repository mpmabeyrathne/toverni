import {
  createHash,
} from 'node:crypto';

import {
  mkdir,
  readFile,
  writeFile,
} from 'node:fs/promises';

import {
  join,
} from 'node:path';

import type {
  BrowserTarget,
} from '../browser/index.js';

import {
  testPlanIrSchema,
  type TestPlanAssertion,
  type TestPlanIr,
  type TestPlanStepOperation,
  type TestPlanTarget,
} from './test-plan-ir.js';

import {
  renderPlaywrightLocator,
} from './playwright-locator-renderer.js';

export interface RenderPlaywrightTestInput {
  plan:
    TestPlanIr;

  targetUrl:
    string;
}

export interface WrittenPlaywrightTest {
  filePath:
    string;

  source:
    string;
}

function quote(
  value:
    string,
): string {
  return JSON.stringify(
    value,
  );
}

function commentText(
  value:
    string,
): string {
  return value
    .replace(
      /\s+/g,
      ' ',
    )
    .trim();
}

function toBrowserTarget(
  target:
    TestPlanTarget,
): BrowserTarget {
  switch (
    target.by
  ) {
    case 'role':
      return {
        by:
          'role',

        role:
          target.role,

        ...(target.name !==
          undefined
          ? {
              name:
                target.name,
            }
          : {}),

        ...(target.exact !==
          undefined
          ? {
              exact:
                target.exact,
            }
          : {}),
      };

    case 'label':
      return {
        by:
          'label',

        label:
          target.label,

        ...(target.exact !==
          undefined
          ? {
              exact:
                target.exact,
            }
          : {}),
      };

    case 'text':
      return {
        by:
          'text',

        text:
          target.text,

        ...(target.exact !==
          undefined
          ? {
              exact:
                target.exact,
            }
          : {}),
      };

    case 'testId':
      return {
        by:
          'testId',

        value:
          target.value,
      };

    case 'css':
      return {
        by:
          'css',

        selector:
          target.selector,
      };
  }
}

const GENERATED_FILE_MARKER =
  '// Generated by Toverni. Do not edit this file by hand.';

function createSafeFileName(
  plan:
    TestPlanIr,
): string {
  const titleSlug =
    plan.title
      .toLowerCase()
      .replace(
        /[^a-z0-9]+/g,
        '-',
      )
      .replace(
        /^-+|-+$/g,
        '',
      )
      .slice(
        0,
        72,
      ) ||
    'generated-test';

  const identity =
    JSON.stringify({
      title:
        plan.title,

      evidenceReferences:
        [
          ...plan.evidenceReferences,
        ].sort(),
    });

  const suffix =
    createHash(
      'sha256',
    )
      .update(
        identity,
      )
      .digest(
        'hex',
      )
      .slice(
        0,
        8,
      );

  return `${titleSlug}-${suffix}`;
}

async function assertSafeToWrite(
  filePath:
    string,

  source:
    string,
): Promise<void> {
  let existing:
    string;

  try {
    existing =
      await readFile(
        filePath,
        'utf8',
      );
  } catch (
    error:
      unknown
  ) {
    if (
      error instanceof Error &&
      'code' in error &&
      error.code ===
        'ENOENT'
    ) {
      return;
    }

    throw error;
  }

  if (
    existing ===
    source
  ) {
    return;
  }

  if (
    existing.startsWith(
      GENERATED_FILE_MARKER,
    )
  ) {
    return;
  }

  throw new Error(
    `Refusing to overwrite existing non-Toverni Playwright spec: ${filePath}`,
  );
}

function compileOperation(
  operation:
    TestPlanStepOperation,
): string {
  switch (
    operation.kind
  ) {
    case 'click':
      return `${renderPlaywrightLocator(
        toBrowserTarget(
          operation.target,
        ),
      )}.click();`;

    case 'fill':
      return `${renderPlaywrightLocator(
        toBrowserTarget(
          operation.target,
        ),
      )}.fill(${quote(
        operation.value,
      )});`;

    case 'select':
      return `${renderPlaywrightLocator(
        toBrowserTarget(
          operation.target,
        ),
      )}.selectOption(${quote(
        operation.value,
      )});`;

    case 'set-checked':
      return `${renderPlaywrightLocator(
        toBrowserTarget(
          operation.target,
        ),
      )}.setChecked(${String(
        operation.checked,
      )});`;

    case 'set-input-files':
      return `${renderPlaywrightLocator(
        toBrowserTarget(
          operation.target,
        ),
      )}.setInputFiles({ name: ${quote(
        operation.file.name,
      )}, mimeType: ${quote(
        operation.file.mimeType,
      )}, buffer: Buffer.from(${quote(
        operation.file.content,
      )}, "utf8") });`;
  }
}

function compileAssertion(
  assertion:
    TestPlanAssertion,
): string {
  const subject =
    assertion.target.kind ===
    'page'
      ? 'page'
      : renderPlaywrightLocator(
          toBrowserTarget(
            assertion.target
              .target,
          ),
        );

  switch (
    assertion.matcher
  ) {
    case 'url':
      if (
        typeof assertion.expected !==
        'string'
      ) {
        throw new Error(
          'URL assertion requires a string expected value.',
        );
      }

      return `expect(${subject}).toHaveURL(${quote(assertion.expected)});`;

    case 'visible':
      return `expect(${subject}).toBeVisible();`;

    case 'hidden':
      return `expect(${subject}).toBeHidden();`;

    case 'enabled':
      return `expect(${subject}).toBeEnabled();`;

    case 'disabled':
      return `expect(${subject}).toBeDisabled();`;

    case 'count':
      if (
        typeof assertion.expected !==
        'number'
      ) {
        throw new Error(
          'Count assertion requires a numeric expected value.',
        );
      }

      return `expect(${subject}).toHaveCount(${assertion.expected});`;

    case 'value':
      if (
        typeof assertion.expected !==
        'string'
      ) {
        throw new Error(
          'Value assertion requires a string expected value.',
        );
      }

      return `expect(${subject}).toHaveValue(${quote(assertion.expected)});`;
  }
}

export function compilePlaywrightTest(
  input:
    RenderPlaywrightTestInput,
): string {
  const plan =
    testPlanIrSchema.parse(
      input.plan,
    );

  if (
    plan.status !==
    'ready'
  ) {
    throw new Error(
      'Cannot render a manual-required test plan.',
    );
  }

  const lines:
    string[] = [
      GENERATED_FILE_MARKER,
      `import { expect, test } from '@playwright/test';`,
      '',
      'const generationMetadata = {',
      `  irVersion: ${quote(plan.metadata.irVersion)},`,
      `  generator: ${quote(plan.metadata.generator)},`,
      `  scenarioId: ${quote(plan.scenarioId)},`,
      `  evidenceReferences: ${JSON.stringify(
        plan.evidenceReferences,
        null,
        2,
      )},`,
      '} as const;',
      '',
      'void generationMetadata;',
      '',
      `test(${quote(
        plan.title,
      )}, async ({ page }) => {`,
      `  await page.goto(${quote(
        input.targetUrl,
      )});`,
      '',
    ];

  for (
    const assertion of
      plan.assertions.filter(
        (item) =>
          item.afterActionId ===
          '__initial__',
      )
  ) {
    lines.push(
      `  // Assertion evidence: ${assertion.evidenceReferences.join(', ')}`,
      `  // ${commentText(assertion.description)}`,
      `  await ${compileAssertion(assertion)}`,
      '',
    );
  }

  for (
    const step of
      plan.steps
  ) {
    lines.push(
      `  // Evidence: ${step.evidenceReference}`,
    );

    lines.push(
      `  // ${commentText(step.description)}`,
    );

    lines.push(
      `  await ${compileOperation(
        step.operation,
      )}`,
    );

    const assertions =
      plan.assertions.filter(
        (assertion) =>
          assertion
            .afterTransitionId
            ? assertion
                .afterTransitionId ===
              step.transitionId
            : assertion
                .afterActionId ===
              step.actionId,
      );

    for (
      const assertion of
        assertions
    ) {
      lines.push(
        `  // Assertion evidence: ${assertion.evidenceReferences.join(', ')}`,
      );

      lines.push(
        `  // ${commentText(assertion.description)}`,
      );

      lines.push(
        `  await ${compileAssertion(
          assertion,
        )}`,
      );
    }

    lines.push('');
  }

  lines.push('});');
  lines.push('');

  return lines.join(
    '\n',
  );
}

export async function writePlaywrightTest(
  input:
    RenderPlaywrightTestInput,

  outputDirectory:
    string,
): Promise<
  WrittenPlaywrightTest
> {
  const source =
    compilePlaywrightTest(
      input,
    );

  await mkdir(
    outputDirectory,
    {
      recursive:
        true,
    },
  );

  const fileName =
    `${createSafeFileName(
      input.plan,
    )}.spec.ts`;

  const filePath =
    join(
      outputDirectory,
      fileName,
    );

  await assertSafeToWrite(
    filePath,
    source,
  );

  await writeFile(
    filePath,
    source,
    'utf8',
  );

  return {
    filePath,
    source,
  };
}


export const renderPlaywrightTest =
  compilePlaywrightTest;
