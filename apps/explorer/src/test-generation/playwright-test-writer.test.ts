import {
  mkdtemp,
  readFile,
  rm,
  writeFile,
} from 'node:fs/promises';

import {
  tmpdir,
} from 'node:os';

import {
  basename,
  join,
} from 'node:path';

import {
  afterEach,
  describe,
  expect,
  it,
} from 'vitest';

import {
  writePlaywrightTest,
} from './playwright-test-renderer.js';

const temporaryDirectories:
  string[] = [];

const readyPlan = {
  scenarioId:
    'random-database-id',

  title:
    'Checkout as returning customer',

  status:
    'ready' as const,

  reason:
    null,

  evidenceReferences: [
    'REQ-CHECKOUT',
    'FLOW-CHECKOUT',
  ],

  metadata: {
    irVersion:
      '1' as const,

    generator:
      'toverni' as const,
  },

  assertions: [],

  steps: [],
};

async function createTemporaryDirectory():
Promise<string> {
  const directory =
    await mkdtemp(
      join(
        tmpdir(),
        'toverni-spec-writer-',
      ),
    );

  temporaryDirectories.push(
    directory,
  );

  return directory;
}

afterEach(
  async () => {
    await Promise.all(
      temporaryDirectories
        .splice(
          0,
        )
        .map(
          (directory) =>
            rm(
              directory,
              {
                recursive:
                  true,

                force:
                  true,
              },
            ),
        ),
    );
  },
);

describe(
  'writePlaywrightTest',
  () => {
    it(
      'uses a readable deterministic filename that does not depend on the stored scenario UUID',
      async () => {
        const outputDirectory =
          await createTemporaryDirectory();

        const first =
          await writePlaywrightTest(
            {
              plan:
                readyPlan,

              targetUrl:
                'https://example.com',
            },
            outputDirectory,
          );

        const second =
          await writePlaywrightTest(
            {
              plan: {
                ...readyPlan,

                scenarioId:
                  'different-database-id',
              },

              targetUrl:
                'https://example.com',
            },
            outputDirectory,
          );

        expect(
          basename(
            first.filePath,
          ),
        ).toMatch(
          /^checkout-as-returning-customer-[a-f0-9]{8}\.spec\.ts$/,
        );

        expect(
          second.filePath,
        ).toBe(
          first.filePath,
        );
      },
    );

    it(
      'marks generated files and can safely refresh Toverni-owned output',
      async () => {
        const outputDirectory =
          await createTemporaryDirectory();

        const written =
          await writePlaywrightTest(
            {
              plan:
                readyPlan,

              targetUrl:
                'https://example.com',
            },
            outputDirectory,
          );

        const source =
          await readFile(
            written.filePath,
            'utf8',
          );

        expect(
          source.startsWith(
            '// Generated by Toverni. Do not edit this file by hand.',
          ),
        ).toBe(
          true,
        );

        await expect(
          writePlaywrightTest(
            {
              plan:
                readyPlan,

              targetUrl:
                'https://example.org',
            },
            outputDirectory,
          ),
        ).resolves.toMatchObject({
          filePath:
            written.filePath,
        });
      },
    );

    it(
      'refuses to overwrite an existing project spec that Toverni does not own',
      async () => {
        const outputDirectory =
          await createTemporaryDirectory();

        const generated =
          await writePlaywrightTest(
            {
              plan:
                readyPlan,

              targetUrl:
                'https://example.com',
            },
            outputDirectory,
          );

        await writeFile(
          generated.filePath,
          'test("hand-written", async () => {});',
          'utf8',
        );

        await expect(
          writePlaywrightTest(
            {
              plan:
                readyPlan,

              targetUrl:
                'https://example.com',
            },
            outputDirectory,
          ),
        ).rejects.toThrow(
          'Refusing to overwrite existing non-Toverni Playwright spec',
        );
      },
    );
  },
);
